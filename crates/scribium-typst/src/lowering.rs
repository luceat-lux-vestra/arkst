//! Typst lowering — converts the Scribium IR into Typst source code.
//!
//! Each IR node type maps to a Typst construct. The lowering pass
//! records source map entries as it generates code.

use scribium_core::ir::{
    IrCallSegment, IrComponent, IrContainerAlignment, IrContainerComponent, IrCrossAxisAlignment,
    IrDocument, IrInline, IrLandscapeComponent, IrMainAxisAlignment, IrNode, IrSize, IrSizeUnit,
    IrStackedComponent, IrStackedLayout, IrTableAlignment, IrTableCell, IrTableRow, IrTaskStatus,
    IrValue, SourceMapEntry,
};
use scribium_core::source::{ResourceReference, SourceSpan};

/// Lower a Scribium IR document to Typst source code.
///
/// Returns the generated Typst source along with a source map that
/// links each generated byte range back to its original source span.
pub fn lower_to_typst(doc: &IrDocument) -> (String, Vec<SourceMapEntry>) {
    let mut ctx = LoweringContext::new();
    ctx.lower_document(doc);
    (ctx.output, ctx.source_map)
}

/// Lower a Scribium IR document to Typst source code without source map.
pub fn lower_to_typst_code(doc: &IrDocument) -> String {
    lower_to_typst(doc).0
}
struct LoweringContext {
    output: String,
    source_map: Vec<SourceMapEntry>,
    /// Current list nesting level (0 = top-level, 1 = nested, etc.)
    list_nesting: usize,
    /// Indentation string for the current list level (used for nested items)
    list_indent: String,
    /// Continuation indent for the list item currently being emitted.
    ///
    /// While non-empty, every newly started line is prefixed with this
    /// string so that all blocks of the current `IrListItem` stay contained
    /// in that item in the generated Typst (Typst list items own every line
    /// indented to at least the item's content column).
    list_item_indent: String,
    /// Whether line starts get the item continuation indent.
    at_line_start: bool,
    /// Whether the raw pushed text must not receive the continuation
    /// indent (verbatim code/raw content inside a list item).
    verbatim: bool,
}

impl LoweringContext {
    fn new() -> Self {
        Self {
            output: String::new(),
            source_map: Vec::new(),
            list_nesting: 0,
            list_indent: String::new(),
            list_item_indent: String::new(),
            at_line_start: false,
            verbatim: false,
        }
    }

    /// Record a source map entry for the generated range just produced.
    fn record_span(&mut self, original: SourceSpan, generated_len: usize) {
        let start = self.output.len().saturating_sub(generated_len);
        let end = self.output.len();
        if start < end {
            self.source_map.push(SourceMapEntry {
                generated_start: start,
                generated_end: end,
                original,
            });
        }
    }

    fn lower_document(&mut self, doc: &IrDocument) {
        // Emit metadata as Typst set-rules
        if let Some(ref title) = doc.metadata.title {
            self.push_str(&format!("// Title: {}\n", title));
        }
        if let Some(ref author) = doc.metadata.author {
            self.push_str(&format!("// Author: {}\n", author));
        }
        if let Some(ref date) = doc.metadata.date {
            self.push_str(&format!("// Date: {}\n", date));
        }

        for node in &doc.nodes {
            let before = self.output.len();
            self.lower_node(node);
            if self.output.len() > before {
                self.push('\n');
            }
        }
    }

    fn lower_node(&mut self, node: &IrNode) {
        match node {
            IrNode::Heading {
                level,
                content,
                span,
            } => {
                let prefix = "=".repeat(*level);
                let before = self.output.len();
                self.push_str(&prefix);
                self.push(' ');
                self.lower_inlines(content);
                self.push('\n');
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrNode::Paragraph { content, span } => {
                let before = self.output.len();
                self.lower_inlines(content);
                if self.output.len() > before {
                    self.push('\n');
                    if span.source_id != scribium_core::SourceId(0) {
                        self.record_span(*span, self.output.len() - before);
                    }
                }
            }
            IrNode::Blockquote { content, span } => {
                let before = self.output.len();
                self.push_str("#quote(block: true)[\n");
                for child in content {
                    self.lower_node(child);
                }
                self.push_str("]\n");
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrNode::UnorderedList { items, span } => {
                let before = self.output.len();
                let was_nested = self.list_nesting > 0;
                if was_nested {
                    self.list_indent.push_str("  ");
                }
                self.list_nesting += 1;
                for item in items {
                    let marker_prefix = if was_nested {
                        format!("{} - ", self.list_indent)
                    } else {
                        "- ".to_string()
                    };
                    self.lower_list_item(&marker_prefix, item);
                }
                self.list_nesting -= 1;
                if was_nested {
                    self.list_indent
                        .truncate(self.list_indent.len().saturating_sub(2));
                }
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrNode::OrderedList { items, start, span } => {
                let before = self.output.len();
                let was_nested = self.list_nesting > 0;
                if was_nested {
                    self.list_indent.push_str("  ");
                }
                self.list_nesting += 1;
                for (i, item) in items.iter().enumerate() {
                    let counter = start + i;
                    let marker_prefix = if was_nested {
                        format!("{}{}. ", self.list_indent, counter)
                    } else {
                        format!("{}. ", counter)
                    };
                    self.lower_list_item(&marker_prefix, item);
                }
                self.list_nesting -= 1;
                if was_nested {
                    self.list_indent
                        .truncate(self.list_indent.len().saturating_sub(2));
                }
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrNode::Table { header, rows, span } => {
                let before = self.output.len();
                self.lower_table(header, rows);
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrNode::CodeBlock {
                language,
                info: _info,
                source,
                span,
            } => {
                let before = self.output.len();
                self.push_str("```");
                if let Some(lang) = language {
                    self.push_str(lang);
                }
                self.push('\n');
                let was_verbatim = std::mem::replace(&mut self.verbatim, true);
                self.push_str(source);
                if !source.ends_with('\n') {
                    self.push('\n');
                }
                self.verbatim = was_verbatim;
                self.push_str("```\n");
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrNode::RawTypst { source, span } => {
                let before = self.output.len();
                let was_verbatim = std::mem::replace(&mut self.verbatim, true);
                self.push_str(source);
                if !source.ends_with('\n') {
                    self.push('\n');
                }
                self.verbatim = was_verbatim;
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrNode::RawHtml { .. } | IrNode::TargetSpecificContent { .. } => {
                // Raw HTML is either rejected by core evaluation or consumed
                // by a future HTML output backend. Typst/PDF intentionally
                // omit both forms without creating source-map ranges.
            }
            IrNode::Component { component } => self.lower_component(component),
            IrNode::FunctionDeclaration { .. } => {
                // Declarations are consumed by the evaluator and are
                // intentionally outputless. This arm keeps direct lowering of
                // pre-evaluation IR deterministic without inventing backend
                // syntax for source-defined functions.
            }
            IrNode::FunctionCall {
                name,
                positional_args,
                named_args,
                body,
                span,
                ..
            } => {
                let before = self.output.len();
                self.push_str("#");
                self.push_str(name);
                if !positional_args.is_empty() || !named_args.is_empty() {
                    self.push('(');
                    let mut first = true;
                    for arg in positional_args {
                        if !first {
                            self.push_str(", ");
                        }
                        self.lower_value(arg);
                        first = false;
                    }
                    for arg in named_args {
                        if !first {
                            self.push_str(", ");
                        }
                        self.push_str(&arg.name);
                        self.push_str(": ");
                        self.lower_value(&arg.value);
                        first = false;
                    }
                    self.push(')');
                }
                if let Some(body_nodes) = body {
                    self.push('[');
                    let saved_item = std::mem::take(&mut self.list_item_indent);
                    for node in body_nodes {
                        self.lower_node(node);
                    }
                    self.list_item_indent = saved_item;
                    self.push(']');
                }
                self.push('\n');
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrNode::ChainedFunctionCall {
                head,
                chain,
                body,
                span,
            } => {
                // Defensive rendering for manually constructed unresolved IR.
                // The normal evaluator resolves successful chains before this
                // lowering pass, and failed chains are rejected by diagnostics.
                let before = self.output.len();
                self.push_str("// Scribium parser-preserved call chain: ");
                self.lower_chain_label(head, chain);
                self.push_str(" (unresolved chain; evaluator did not resolve it)\n");
                if let Some(body_nodes) = body {
                    for node in body_nodes {
                        self.lower_node(node);
                    }
                }
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrNode::ThematicBreak { span } => {
                let before = self.output.len();
                self.push_str("---\n");
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrNode::Math {
                source,
                display,
                span,
            } => {
                let before = self.output.len();
                if *display {
                    self.push_str("$ ");
                    self.push_str(source);
                    self.push_str(" $\n");
                } else {
                    self.push('$');
                    self.push_str(source);
                    self.push('$');
                }
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
        }
    }

    fn lower_component(&mut self, component: &IrComponent) {
        match component {
            IrComponent::Stacked(stacked) => self.lower_stacked(stacked),
            IrComponent::Container(container) => self.lower_container(container),
            IrComponent::Landscape(landscape) => self.lower_landscape(landscape),
        }
    }

    fn lower_landscape(&mut self, component: &IrLandscapeComponent) {
        let before = self.output.len();
        self.push_str("#rotate(-90deg, reflow: true)[\n");
        for child in &component.children {
            self.lower_node(child);
        }
        self.push_str("]\n");
        if component.span.source_id != scribium_core::SourceId(0) {
            self.record_span(component.span, self.output.len() - before);
        }
    }

    fn lower_container(&mut self, component: &IrContainerComponent) {
        let before = self.output.len();
        self.push_str("#block");
        let width = component.width.as_ref();
        if width.is_some() || component.full_width || component.height.is_some() {
            self.push('(');
            let mut first = true;
            if let Some(width) = width {
                self.push_str("width: ");
                self.push_str(&lower_size(width));
                first = false;
            } else if component.full_width {
                self.push_str("width: 100%");
                first = false;
            }
            if let Some(height) = component.height.as_ref() {
                if !first {
                    self.push_str(", ");
                }
                self.push_str("height: ");
                self.push_str(&lower_size(height));
            }
            self.push(')');
        }
        self.push_str("[\n");
        if let Some(alignment) = component.alignment {
            self.push_str("#align(");
            self.push_str(match alignment {
                IrContainerAlignment::Start => "start",
                IrContainerAlignment::Center => "center",
                IrContainerAlignment::End => "end",
            });
            self.push_str(")[\n");
        }
        for child in &component.children {
            self.lower_node(child);
        }
        if component.alignment.is_some() {
            self.push_str("]\n");
        }
        self.push(']');
        self.push('\n');
        if component.span.source_id != scribium_core::SourceId(0) {
            self.record_span(component.span, self.output.len() - before);
        }
    }

    fn lower_stacked(&mut self, component: &IrStackedComponent) {
        let before = self.output.len();
        match &component.layout {
            IrStackedLayout::Row => self.lower_stack(
                component,
                "ltr",
                component.row_gap.as_ref().or(component.column_gap.as_ref()),
            ),
            IrStackedLayout::Column => self.lower_stack(
                component,
                "ttb",
                component.row_gap.as_ref().or(component.column_gap.as_ref()),
            ),
            IrStackedLayout::Grid { columns } => self.lower_grid(component, columns.get()),
        }
        if component.span.source_id != scribium_core::SourceId(0) {
            self.record_span(component.span, self.output.len() - before);
        }
    }

    fn lower_stack(
        &mut self,
        component: &IrStackedComponent,
        direction: &str,
        gap: Option<&IrSize>,
    ) {
        let horizontal = direction == "ltr";
        self.push_str("#stack(dir: ");
        self.push_str(direction);
        self.push_str(", ");
        let distribution = component.main_axis_alignment;
        let child_count = component.children.len();
        if matches!(
            distribution,
            IrMainAxisAlignment::SpaceBetween
                | IrMainAxisAlignment::SpaceAround
                | IrMainAxisAlignment::SpaceEvenly
        ) {
            self.lower_distributed_stack(component, horizontal, gap, child_count, distribution);
        } else if child_count == 0 {
            self.push_str("[]");
        } else {
            if matches!(
                distribution,
                IrMainAxisAlignment::Center | IrMainAxisAlignment::End
            ) {
                self.lower_fraction(horizontal, "1fr");
                self.push_str(", ");
            }
            for (index, child) in component.children.iter().enumerate() {
                self.lower_stacked_child(child, component.cross_axis_alignment, horizontal);
                if index + 1 < child_count {
                    self.push_str(", ");
                    if let Some(gap) = gap {
                        self.lower_fixed_gap(horizontal, gap);
                        self.push_str(", ");
                    }
                }
            }
            if matches!(distribution, IrMainAxisAlignment::Center) {
                self.push_str(", ");
                self.lower_fraction(horizontal, "1fr");
            }
        }
        self.push_str(")\n");
    }

    fn lower_distributed_stack(
        &mut self,
        component: &IrStackedComponent,
        horizontal: bool,
        gap: Option<&IrSize>,
        child_count: usize,
        distribution: IrMainAxisAlignment,
    ) {
        if child_count == 0 {
            self.push_str("[]");
            return;
        }
        let edge_fraction = match distribution {
            IrMainAxisAlignment::SpaceAround => Some("0.5fr"),
            IrMainAxisAlignment::SpaceEvenly => Some("1fr"),
            IrMainAxisAlignment::SpaceBetween => None,
            _ => None,
        };
        if let Some(fraction) = edge_fraction {
            self.lower_fraction(horizontal, fraction);
            self.push_str(", ");
        }
        for (index, child) in component.children.iter().enumerate() {
            self.lower_stacked_child(child, component.cross_axis_alignment, horizontal);
            if index + 1 < child_count {
                self.push_str(", ");
                if let Some(gap) = gap {
                    self.lower_fixed_gap(horizontal, gap);
                    self.push_str(", ");
                }
                self.lower_fraction(horizontal, "1fr");
                self.push_str(", ");
            }
        }
        if let Some(fraction) = edge_fraction {
            self.push_str(", ");
            self.lower_fraction(horizontal, fraction);
        }
    }

    fn lower_fixed_gap(&mut self, horizontal: bool, gap: &IrSize) {
        self.push_str(if horizontal { "h(" } else { "v(" });
        self.push_str(&lower_size(gap));
        self.push(')');
    }

    fn lower_fraction(&mut self, horizontal: bool, fraction: &str) {
        self.push_str(if horizontal { "h(" } else { "v(" });
        self.push_str(fraction);
        self.push(')');
    }

    fn lower_stacked_child(
        &mut self,
        child: &IrNode,
        cross_axis: IrCrossAxisAlignment,
        horizontal_stack: bool,
    ) {
        self.push('[');
        match (horizontal_stack, cross_axis) {
            (true, IrCrossAxisAlignment::Start) => self.lower_with_alignment("top", child),
            (true, IrCrossAxisAlignment::Center) => self.lower_with_alignment("horizon", child),
            (true, IrCrossAxisAlignment::End) => self.lower_with_alignment("bottom", child),
            (true, IrCrossAxisAlignment::Stretch) => {
                self.push_str("#block(height: 100%)[");
                self.lower_node(child);
                self.push(']');
            }
            (false, IrCrossAxisAlignment::Start) => self.lower_with_alignment("left", child),
            (false, IrCrossAxisAlignment::Center) => self.lower_with_alignment("center", child),
            (false, IrCrossAxisAlignment::End) => self.lower_with_alignment("right", child),
            (false, IrCrossAxisAlignment::Stretch) => {
                self.push_str("#block(width: 100%)[");
                self.lower_node(child);
                self.push(']');
            }
        }
        self.push(']');
    }

    fn lower_with_alignment(&mut self, alignment: &str, child: &IrNode) {
        self.push_str("#align(");
        self.push_str(alignment);
        self.push(')');
        self.push('[');
        self.lower_node(child);
        self.push(']');
    }

    fn lower_grid(&mut self, component: &IrStackedComponent, columns: u32) {
        let main_alignment = match component.main_axis_alignment {
            IrMainAxisAlignment::Start => "left",
            IrMainAxisAlignment::Center => "center",
            IrMainAxisAlignment::End => "right",
            IrMainAxisAlignment::SpaceBetween
            | IrMainAxisAlignment::SpaceAround
            | IrMainAxisAlignment::SpaceEvenly => "left",
        };
        let distributed = matches!(
            component.main_axis_alignment,
            IrMainAxisAlignment::SpaceBetween
                | IrMainAxisAlignment::SpaceAround
                | IrMainAxisAlignment::SpaceEvenly
        );
        if distributed {
            self.lower_distributed_grid(component, columns);
            return;
        }
        if main_alignment != "left" {
            self.push_str("#align(");
            self.push_str(main_alignment);
            self.push(')');
            self.push('[');
        }
        self.push_str("#grid(columns: ");
        self.push_str(&columns.to_string());
        if let Some(gap) = component.row_gap.as_ref() {
            self.push_str(", row-gutter: ");
            self.push_str(&lower_size(gap));
        }
        if let Some(gap) = component.column_gap.as_ref() {
            self.push_str(", column-gutter: ");
            self.push_str(&lower_size(gap));
        }
        if component.children.is_empty() {
            self.push_str(", []");
        } else {
            self.push_str(", ");
            for (index, child) in component.children.iter().enumerate() {
                if index > 0 {
                    self.push_str(", ");
                }
                self.lower_stacked_child(child, component.cross_axis_alignment, true);
            }
        }
        self.push(')');
        if main_alignment != "left" {
            self.push(']');
        }
        self.push('\n');
    }

    fn lower_distributed_grid(&mut self, component: &IrStackedComponent, columns: u32) {
        let logical_columns = columns as usize;
        let edge_fraction = match component.main_axis_alignment {
            IrMainAxisAlignment::SpaceAround => Some("0.5fr"),
            IrMainAxisAlignment::SpaceEvenly => Some("1fr"),
            IrMainAxisAlignment::SpaceBetween => None,
            _ => None,
        };
        if component.children.is_empty() {
            self.push_str("#grid(columns: ");
            self.push_str(&columns.to_string());
            if let Some(gap) = component.row_gap.as_ref() {
                self.push_str(", row-gutter: ");
                self.push_str(&lower_size(gap));
            }
            self.push_str(", [])\n");
            return;
        }
        let fixed_gap = component.column_gap.as_ref().map(lower_size);
        self.push_str("#grid(columns: (");
        if let Some(fraction) = edge_fraction {
            self.push_str(fraction);
            self.push_str(", ");
        }
        for index in 0..logical_columns {
            if index > 0 {
                self.push_str(", ");
                if let Some(gap) = fixed_gap.as_deref() {
                    self.push_str(gap);
                    self.push_str(", ");
                }
                self.push_str("1fr, ");
            }
            self.push_str("auto");
        }
        if let Some(fraction) = edge_fraction {
            self.push_str(", ");
            self.push_str(fraction);
        }
        self.push(')');
        if let Some(gap) = component.row_gap.as_ref() {
            self.push_str(", row-gutter: ");
            self.push_str(&lower_size(gap));
        }
        self.push_str(", ");

        for (row_index, row) in component.children.chunks(logical_columns).enumerate() {
            if row_index > 0 {
                self.push_str(", ");
            }
            if edge_fraction.is_some() {
                self.push_str("[], ");
            }
            for column_index in 0..logical_columns {
                if column_index > 0 {
                    self.push_str(", ");
                    if fixed_gap.is_some() {
                        self.push_str("[], ");
                    }
                    self.push_str("[], ");
                }
                if let Some(child) = row.get(column_index) {
                    self.lower_stacked_child(child, component.cross_axis_alignment, true);
                } else {
                    self.push_str("[]");
                }
            }
            if edge_fraction.is_some() {
                self.push_str(", []");
            }
        }
        self.push_str(")\n");
    }

    fn lower_inlines(&mut self, inlines: &[IrInline]) {
        for inline in inlines {
            self.lower_inline(inline);
        }
    }

    fn lower_inline(&mut self, inline: &IrInline) {
        match inline {
            IrInline::Text { content, span } => {
                let before = self.output.len();
                self.push_str(&escape_typst_text(content));
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::Whitespace {
                width,
                height,
                span,
            } => {
                let before = self.output.len();
                if width.is_none() && height.is_none() {
                    self.push('\u{a0}');
                } else {
                    let zero = IrSize {
                        value: 0.0,
                        unit: IrSizeUnit::Pt,
                    };
                    self.push_str("#box(width: ");
                    self.push_str(&lower_size(width.as_ref().unwrap_or(&zero)));
                    self.push_str(", height: ");
                    self.push_str(&lower_size(height.as_ref().unwrap_or(&zero)));
                    self.push_str(")[]");
                }
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::RawHtml { .. } | IrInline::TargetSpecificContent { .. } => {
                // Target-specific HTML and parser-owned raw HTML never become
                // Typst source or visible placeholder text.
            }
            IrInline::Emphasis { content, span } => {
                let before = self.output.len();
                self.push('*');
                self.lower_inlines(content);
                self.push('*');
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::Strong { content, span } => {
                let before = self.output.len();
                self.push_str("*");
                self.lower_inlines(content);
                self.push_str("*");
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::Strikethrough { content, span } => {
                let before = self.output.len();
                self.push_str("#strike[");
                self.lower_inlines(content);
                self.push(']');
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::DirectiveCall {
                name,
                positional_args,
                named_args,
                body,
                span,
            } => {
                let before = self.output.len();
                self.push_str("#");
                self.push_str(name);
                if !positional_args.is_empty() || !named_args.is_empty() {
                    self.push('(');
                    let mut first = true;
                    for arg in positional_args {
                        if !first {
                            self.push_str(", ");
                        }
                        self.lower_value(arg);
                        first = false;
                    }
                    for arg in named_args {
                        if !first {
                            self.push_str(", ");
                        }
                        self.push_str(&arg.name);
                        self.push_str(": ");
                        self.lower_value(&arg.value);
                        first = false;
                    }
                    self.push(')');
                }
                if let Some(body_inlines) = body {
                    self.push('[');
                    self.lower_inlines(body_inlines);
                    self.push(']');
                }
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::ChainedDirectiveCall {
                head,
                chain,
                body,
                span,
            } => {
                // Defensive rendering for manually constructed unresolved IR.
                // The normal evaluator resolves successful chains before this
                // lowering pass, and failed chains are rejected by diagnostics.
                let before = self.output.len();
                self.push_str("/* Scribium parser-preserved call chain: ");
                self.lower_chain_label(head, chain);
                self.push_str("; unresolved chain; evaluator did not resolve it */");
                if let Some(body_inlines) = body {
                    self.push('[');
                    self.lower_inlines(body_inlines);
                    self.push(']');
                }
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::Link {
                content,
                destination,
                title: _title,
                span,
            } => {
                let before = self.output.len();
                self.push_str("#link(");
                self.push('"');
                self.push_str(&escape_typst_string(destination));
                self.push('"');
                self.push(')');
                self.push('[');
                self.lower_inlines(content);
                self.push(']');
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::Image {
                destination,
                title,
                span,
                ..
            } => {
                let before = self.output.len();
                if ResourceReference::classify(destination).is_local_path() {
                    self.push_str("#image(\"");
                    self.push_str(&escape_typst_string(destination));
                    self.push_str("\")");
                } else {
                    // Core compilation diagnoses non-local Markdown image
                    // references. Keep defensive direct-IR lowering
                    // non-fetching if a caller bypasses that diagnostic gate.
                    self.push_str("/* Scribium image resource rejected: ");
                    self.push_str(&escape_typst_comment(destination));
                    if let Some(title) = title {
                        self.push_str("; title: ");
                        self.push_str(&escape_typst_comment(title));
                    }
                    self.push_str(" */");
                }
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::SoftBreak { span } => {
                let before = self.output.len();
                self.push('\n');
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::HardBreak { span } => {
                let before = self.output.len();
                self.push_str("\\\n");
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
            IrInline::Code { content, span } => {
                let before = self.output.len();
                self.push_str("#raw(");
                self.push('"');
                self.push_str(&escape_typst_string(content));
                self.push('"');
                self.push(')');
                if span.source_id != scribium_core::SourceId(0) {
                    self.record_span(*span, self.output.len() - before);
                }
            }
        }
    }

    fn lower_value(&mut self, value: &IrValue) {
        match value {
            IrValue::String(s) => {
                // Escape Typst string characters
                let escaped = escape_typst_string(s);
                self.push('"');
                self.push_str(&escaped);
                self.push('"');
            }
            IrValue::Number(n) => {
                self.push_str(&n.to_string());
            }
            IrValue::Boolean(b) => {
                self.push_str(if *b { "true" } else { "false" });
            }
            IrValue::Identifier(id) => {
                // A bare identifier argument is emitted as a string literal so
                // the generated Typst always compiles. Semantic resolution
                // against a function signature is the evaluator's job.
                let escaped = escape_typst_string(id);
                self.push('"');
                self.push_str(&escaped);
                self.push('"');
            }
            IrValue::None => {
                // Semantic None remains distinct from the observable text
                // materialized by the evaluator at an output boundary.
                self.push_str("none");
            }
            IrValue::Range(_) => {
                // Successful evaluation consumes ranges before lowering. Keep
                // defensive lowering typed and explicit without inventing a
                // direct display form for Range values. This branch is only
                // for manually constructed/pre-evaluation IR; normal user
                // documents receive an evaluator diagnostic before reaching
                // the backend.
                self.push_str(
                    "panic(\"Scribium typed Range reached Typst lowering without a semantic consumer\")",
                );
            }
            IrValue::Collection(values) => {
                self.push('[');
                for (index, value) in values.iter().enumerate() {
                    if index > 0 {
                        self.push_str(", ");
                    }
                    self.lower_value(value);
                }
                self.push(']');
            }
            IrValue::Pair(_) | IrValue::Dictionary(_) => {
                // Structured values are consumed by the evaluator (iteration,
                // destructuring, or document-output materialization) before
                // they reach this backend. This defensive branch keeps the
                // backend neutral and makes an invalid pre-evaluation IR
                // explicit instead of inventing Typst data semantics here.
                self.push_str(
                    "panic(\"Scribium structured value reached Typst lowering without a semantic consumer\")",
                );
            }
            IrValue::Content(nodes) => {
                self.push('[');
                let saved_item = std::mem::take(&mut self.list_item_indent);
                for node in nodes {
                    self.lower_node(node);
                }
                self.list_item_indent = saved_item;
                self.push(']');
            }
            IrValue::Callable(callable) => {
                // A callable is evaluator-owned semantic state. Successful
                // documents consume it before lowering; this comment keeps
                // manually constructed invalid IR non-executable and avoids
                // inventing a Typst callable representation.
                let before = self.output.len();
                self.push_str(
                    "/* Scribium callable reached Typst lowering without evaluator consumption */",
                );
                if callable.span.source_id != scribium_core::SourceId(0) {
                    self.record_span(callable.span, self.output.len() - before);
                }
            }
            IrValue::Size(_) | IrValue::Color(_) | IrValue::Enum(_) => {
                // Domain values are evaluator-owned semantic inputs. This is
                // a defensive invalid-IR marker only; Size/Color/enum
                // lowering is intentionally deferred until a real consumer
                // establishes its backend-neutral output contract.
                self.push_str(
                    "panic(\"Scribium domain value reached Typst lowering without a semantic consumer\")",
                );
            }
            IrValue::Component(component) => {
                // Components are evaluator-owned semantic values. They must
                // fail before reaching this backend until a typed component
                // node and its lossless lowering contract land together.
                let before = self.output.len();
                self.push_str(
                    "panic(\"Scribium component reached Typst lowering without a semantic consumer\")",
                );
                if component.span().source_id != scribium_core::SourceId(0) {
                    self.record_span(component.span(), self.output.len() - before);
                }
            }
        }
    }

    fn lower_chain_label(&mut self, head: &IrCallSegment, chain: &[IrCallSegment]) {
        self.push('.');
        self.push_str(&head.name);
        for segment in chain {
            self.push_str("::");
            self.push_str(&segment.name);
        }
    }

    fn push(&mut self, ch: char) {
        if ch != '\n' {
            self.inject_item_indent();
        }
        self.output.push(ch);
        if ch == '\n' {
            self.at_line_start = true;
        }
    }

    fn push_str(&mut self, s: &str) {
        self.inject_item_indent();
        self.output.push_str(s);
        if s.ends_with('\n') {
            self.at_line_start = true;
        }
    }

    fn inject_item_indent(&mut self) {
        if self.at_line_start && !self.verbatim && !self.list_item_indent.is_empty() {
            self.output.push_str(&self.list_item_indent);
            self.at_line_start = false;
        }
    }

    /// Lower every block of the current `IrListItem` so the item's
    /// continuation indent is applied at each block boundary.
    fn lower_list_item(&mut self, marker_prefix: &str, item: &scribium_core::ir::IrListItem) {
        let before = self.output.len();
        let saved = std::mem::replace(&mut self.list_item_indent, " ".repeat(marker_prefix.len()));
        self.at_line_start = false;
        self.push_str(marker_prefix);
        if let Some(task) = item.task {
            self.push_str(match task {
                IrTaskStatus::Active => "☐ ",
                IrTaskStatus::Completed => "☑ ",
            });
        }
        for child in &item.nodes {
            self.lower_item_block(child);
        }
        self.list_item_indent = saved;
        self.push('\n');
        if item.span.source_id != scribium_core::SourceId(0) {
            self.record_span(item.span, self.output.len() - before);
        }
    }

    fn lower_table(&mut self, header: &IrTableRow, rows: &[IrTableRow]) {
        let columns = header
            .cells
            .len()
            .max(rows.iter().map(|row| row.cells.len()).max().unwrap_or(0))
            .max(1);
        self.push_str("#table(\n");
        self.push_str(&format!("  columns: {columns},\n"));
        let header_before = self.output.len();
        self.push_str("  table.header(");
        self.lower_table_cells(&header.cells, columns);
        self.push_str("),\n");
        if header.span.source_id != scribium_core::SourceId(0) {
            self.record_span(header.span, self.output.len() - header_before);
        }
        for row in rows {
            let row_before = self.output.len();
            self.push_str("  ");
            self.lower_table_cells(&row.cells, columns);
            self.push_str(",\n");
            if row.span.source_id != scribium_core::SourceId(0) {
                self.record_span(row.span, self.output.len() - row_before);
            }
        }
        self.push_str(")\n");
    }

    fn lower_table_cells(&mut self, cells: &[IrTableCell], columns: usize) {
        for index in 0..columns {
            if index > 0 {
                self.push_str(", ");
            }
            if let Some(cell) = cells.get(index) {
                self.lower_table_cell(cell);
            } else {
                self.push_str("table.cell(align: auto)[]");
            }
        }
    }

    fn lower_table_cell(&mut self, cell: &IrTableCell) {
        let before = self.output.len();
        self.push_str("table.cell(align: ");
        self.push_str(table_alignment_name(cell.alignment));
        self.push_str(")[");
        self.lower_inlines(&cell.content);
        self.push(']');
        if cell.span.source_id != scribium_core::SourceId(0) {
            self.record_span(cell.span, self.output.len() - before);
        }
    }

    fn lower_item_block(&mut self, node: &IrNode) {
        match node {
            // Nested lists carry their own indentation (`list_indent`), so
            // the item continuation indent must not be re-applied to them.
            IrNode::UnorderedList { .. } | IrNode::OrderedList { .. } => {
                let saved = std::mem::take(&mut self.list_item_indent);
                self.lower_node(node);
                self.list_item_indent = saved;
            }
            _ => self.lower_node(node),
        }
    }
}

fn lower_size(size: &IrSize) -> String {
    let (value, unit) = match size.unit {
        IrSizeUnit::Px => (size.value * 0.75, "pt"),
        IrSizeUnit::Pt => (size.value, "pt"),
        IrSizeUnit::Cm => (size.value, "cm"),
        IrSizeUnit::Mm => (size.value, "mm"),
        IrSizeUnit::In => (size.value, "in"),
        IrSizeUnit::Em => (size.value, "em"),
        IrSizeUnit::Percent => (size.value, "%"),
    };
    format!("{}{unit}", format_number(value))
}

fn format_number(value: f64) -> String {
    let mut text = format!("{value:.12}");
    while text.contains('.') && text.ends_with('0') {
        text.pop();
    }
    if text.ends_with('.') {
        text.pop();
    }
    if text == "-0" {
        "0".to_string()
    } else {
        text
    }
}

fn table_alignment_name(alignment: IrTableAlignment) -> &'static str {
    match alignment {
        IrTableAlignment::Left => "left",
        IrTableAlignment::Center => "center",
        IrTableAlignment::Right => "right",
        IrTableAlignment::None => "auto",
    }
}

/// Escape characters that are special inside a double-quoted Typst string:
/// backslashes and double quotes.
fn escape_typst_string(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Escape Markdown text before inserting it into Typst markup. The frontend
/// has already removed Markdown escapes, so this boundary must prevent those
/// literal characters from becoming Typst formatting or labels.
fn escape_typst_text(s: &str) -> String {
    let mut escaped = String::with_capacity(s.len());
    for character in s.chars() {
        match character {
            '\\' => escaped.push_str("\\\\"),
            '*' | '_' | '~' | '#' | '$' | '<' | '>' | '@' | '[' | ']' => {
                escaped.push('\\');
                escaped.push(character);
            }
            _ => escaped.push(character),
        }
    }
    escaped
}

fn escape_typst_comment(s: &str) -> String {
    s.replace("*/", "* /")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
}

